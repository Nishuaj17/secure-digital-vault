package com.example.securedigitalvault.data.prefs;

import android.content.Context;
import android.content.SharedPreferences;
import android.util.Log;

import androidx.security.crypto.EncryptedSharedPreferences;
import androidx.security.crypto.MasterKey;

import java.io.IOException;
import java.security.GeneralSecurityException;

/**
 * AppPreferences
 *
 * Wraps EncryptedSharedPreferences to store:
 *   - Whether the vault has completed first-time setup
 *   - The PIN's PBKDF2 hash + salt (NOT the raw PIN itself)
 *   - Whether biometric unlock is enabled
 *   - Auto-lock timeout preference
 *
 * WHY EncryptedSharedPreferences instead of plain SharedPreferences?
 * EncryptedSharedPreferences automatically encrypts both keys and values
 * using a key that lives in the Android Keystore. This means even the
 * PIN hash + salt file is protected at rest, not just relying on normal
 * app-sandboxing. This is a defense-in-depth measure on top of the fact
 * that we only ever store a one-way hash, never the actual PIN.
 *
 * SECURITY NOTE: This class must NEVER be used to store:
 *   - The raw PIN itself
 *   - Decrypted passwords, card numbers, or note contents
 *   - Any vault entry data
 * Those all belong in the encrypted Room database or encrypted files,
 * which we build in later phases. This class is strictly for small
 * app-level settings and the PIN verification hash.
 */
public class AppPreferences {

    private static final String TAG = "AppPreferences";
    private static final String PREFS_FILE_NAME = "secure_vault_prefs";

    // Preference keys
    private static final String KEY_IS_SETUP_COMPLETE = "is_setup_complete";
    private static final String KEY_PIN_HASH = "pin_hash";
    private static final String KEY_PIN_SALT = "pin_salt";
    private static final String KEY_BIOMETRIC_ENABLED = "biometric_enabled";
    private static final String KEY_AUTO_LOCK_MINUTES = "auto_lock_minutes";

    private final SharedPreferences sharedPreferences;

    public AppPreferences(Context context) {
        SharedPreferences prefs;
        try {
            MasterKey masterKey = new MasterKey.Builder(context)
                    .setKeyScheme(MasterKey.KeyScheme.AES256_GCM)
                    .build();

            prefs = EncryptedSharedPreferences.create(
                    context,
                    PREFS_FILE_NAME,
                    masterKey,
                    EncryptedSharedPreferences.PrefKeyEncryptionScheme.AES256_SIV,
                    EncryptedSharedPreferences.PrefValueEncryptionScheme.AES256_GCM
            );
        } catch (GeneralSecurityException | IOException e) {
            // If encrypted prefs fail to initialize (extremely rare, usually
            // only on a corrupted Keystore state), we deliberately do NOT
            // fall back to plain SharedPreferences for PIN-related data,
            // since that would silently weaken security. We log a safe,
            // non-sensitive message and rethrow so the app can show the
            // user a clear "security initialization failed" error instead
            // of continuing in an insecure state.
            Log.e(TAG, "Failed to initialize encrypted preferences.");
            throw new RuntimeException("Could not initialize secure storage.", e);
        }
        this.sharedPreferences = prefs;
    }

    public boolean isSetupComplete() {
        return sharedPreferences.getBoolean(KEY_IS_SETUP_COMPLETE, false);
    }

    public void setSetupComplete(boolean complete) {
        sharedPreferences.edit().putBoolean(KEY_IS_SETUP_COMPLETE, complete).apply();
    }

    /**
     * Stores the PIN hash and salt generated by PinHasher.
     * Call this once during setup, or when the user changes their PIN.
     */
    public void savePinHash(String pinHash, String encodedSalt) {
        sharedPreferences.edit()
                .putString(KEY_PIN_HASH, pinHash)
                .putString(KEY_PIN_SALT, encodedSalt)
                .apply();
    }

    public String getPinHash() {
        return sharedPreferences.getString(KEY_PIN_HASH, null);
    }

    public String getPinSalt() {
        return sharedPreferences.getString(KEY_PIN_SALT, null);
    }

    public boolean isBiometricEnabled() {
        return sharedPreferences.getBoolean(KEY_BIOMETRIC_ENABLED, false);
    }

    public void setBiometricEnabled(boolean enabled) {
        sharedPreferences.edit().putBoolean(KEY_BIOMETRIC_ENABLED, enabled).apply();
    }

    /**
     * Auto-lock timeout in minutes. 0 means "lock immediately".
     * Default is 1 minute if never explicitly set.
     */
    public int getAutoLockMinutes() {
        return sharedPreferences.getInt(KEY_AUTO_LOCK_MINUTES, 1);
    }

    public void setAutoLockMinutes(int minutes) {
        sharedPreferences.edit().putInt(KEY_AUTO_LOCK_MINUTES, minutes).apply();
    }
}


